#!/usr/bin/env python3
"""Build PROGRESS.md from every problem's REVIEW.md.

Usage:  python3 tools/scoreboard.py          (run from anywhere inside the repo)

It reads the three header lines of each REVIEW.md:
    Status: not-started | in-progress | solved
    Self-score: <0-20 or ->
    Reviewer-score: <0-20 or ->
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEVELS = os.path.join(ROOT, "levels")
NAMES = {"0": "Foundations", "1": "Warm-up", "2": "Building blocks", "3": "Realistic", "4": "Hard", "5": "Boss"}


def field(text, name):
    m = re.search(rf"^{name}:\s*(.+?)\s*$", text, re.M)
    return m.group(1) if m else "-"


def score(v):
    try:
        return float(v)
    except ValueError:
        return None


def grade(s):
    if s is None:
        return ""
    return "S" if s >= 18 else "A" if s >= 15 else "B" if s >= 12 else "C" if s >= 8 else "D"


def title_of(folder):
    try:
        with open(os.path.join(folder, "PROBLEM.md"), encoding="utf-8") as f:
            return f.readline().lstrip("# ").strip()
    except OSError:
        return os.path.basename(folder)


def main():
    rows = []
    for level in sorted(os.listdir(LEVELS)):
        lp = os.path.join(LEVELS, level)
        if not os.path.isdir(lp):
            continue
        lvl = level.split("-")[1]
        for prob in sorted(os.listdir(lp)):
            pp = os.path.join(lp, prob)
            rv = os.path.join(pp, "REVIEW.md")
            if not os.path.isfile(rv):
                continue
            with open(rv, encoding="utf-8") as f:
                t = f.read()
            app = prob.split("-", 1)[1] if "-" in prob else prob
            rows.append({
                "level": lvl, "folder": os.path.relpath(pp, ROOT).replace(os.sep, "/"),
                "title": title_of(pp), "app": app,
                "status": field(t, "Status"), "self": field(t, "Self-score"), "rev": field(t, "Reviewer-score"),
            })

    solved = [r for r in rows if r["status"] == "solved"]
    progress = [r for r in rows if r["status"] == "in-progress"]
    scored = [score(r["rev"]) if score(r["rev"]) is not None else score(r["self"]) for r in solved]
    scored = [s for s in scored if s is not None]

    out = ["# Progress", "",
           "_Generated by `python3 tools/scoreboard.py` — do not edit by hand._", "",
           f"**{len(solved)} / {len(rows)} solved** · {len(progress)} in progress"
           + (f" · average score **{sum(scored) / len(scored):.1f} / 20**" if scored else ""), ""]

    out += ["| Level | Solved | Bar |", "|------:|-------:|-----|"]
    for lvl in sorted({r["level"] for r in rows}):
        lv = [r for r in rows if r["level"] == lvl]
        done = sum(1 for r in lv if r["status"] == "solved")
        bar = "█" * done + "░" * (len(lv) - done)
        out.append(f"| {lvl} {NAMES.get(lvl, '')} | {done}/{len(lv)} | `{bar}` |")
    out.append("")

    out += ["| Level | Problem | Status | Self | Reviewer | Grade |", "|------:|---------|--------|-----:|---------:|:-----:|"]
    icon = {"solved": "✅ solved", "in-progress": "🟡 in progress"}
    for r in rows:
        final = score(r["rev"]) if score(r["rev"]) is not None else score(r["self"])
        out.append(f"| {r['level']} | [{r['title']}]({r['folder']}/PROBLEM.md) | {icon.get(r['status'], '⬜')} "
                   f"| {r['self']} | {r['rev']} | {grade(final) if r['status'] == 'solved' else ''} |")

    with open(os.path.join(ROOT, "PROGRESS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"PROGRESS.md updated: {len(solved)}/{len(rows)} solved")


if __name__ == "__main__":
    main()
